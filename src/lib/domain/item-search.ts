export function normalizeItemText(s: string): string {
  let t = s.normalize("NFKC").toLowerCase();
  // カタカナ → ひらがな
  t = t.replace(/[ァ-ヶ]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0x60));
  for (const [kanji, kana] of READINGS) t = t.split(kanji).join(kana);
  // 空白・中黒・長音の揺れを除く
  return t.replace(/[\s・･]/g, "");
}

// 検索語が商品名に含まれる（または商品名が検索語に含まれる）か
export function itemMatches(itemName: string, query: string): boolean {
  const q = normalizeItemText(query);
  if (!q) return false;
  const n = normalizeItemText(itemName);
  return n.includes(q) || q.includes(n);
}
