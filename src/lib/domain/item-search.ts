// 食材名の表記ゆれをそろえて検索する（AIは使わない）
// ひらがな・カタカナ・全角半角・空白をそろえ、よく使う漢字表記は読み（ひらがな）に置き換えてから比べる。
// 商品名・品種名そのものは変えない（検索の照合だけに使う）。数量・地域・日程などの条件はこれとは別に必ず適用する。

// 漢字表記 → 読み。長い語から先に置き換える（「玉葱」を「葱」より先に）
